  function lang() {
    const v = storeGet() || "en";
    return D[v] ? v : "en";
  }
  function setLang(code) {
    const v = D[code] ? code : "en";
    storeSet(v);
    apply();
    document.dispatchEvent(new CustomEvent("preclinic:lang", { detail: v }));
    return v;
  }
  function t(key, vars) {
    const table = D[lang()] || D.en;
    let s = table[key] || D.en[key] || key;
    if (vars) Object.keys(vars).forEach((k) => { s = s.replace("{" + k + "}", vars[k]); });
    return s;
  }
  function apply(root) {
    const scope = root || document;
    document.documentElement.lang = lang();
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    scope.querySelectorAll(".lang-switch button[data-lang]").forEach((b) => {
      b.classList.toggle("on", b.getAttribute("data-lang") === lang());
    });
    scope.querySelectorAll("[data-lang].lang-opt").forEach((b) => {
      b.classList.toggle("on", b.getAttribute("data-lang") === lang());
    });
  }
  function bindSwitch(root) {
    (root || document).querySelectorAll("[data-lang]").forEach((b) => {
      if (b.dataset.i18nBound) return;
      b.dataset.i18nBound = "1";
      b.addEventListener("click", () => setLang(b.getAttribute("data-lang")));
    });
  }
  function speechLocale() { return SPEECH[lang()] || "en-IN"; }

  global.PreclinicI18n = { t, lang, setLang, apply, bindSwitch, speechLocale, dict: D };
